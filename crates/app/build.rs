use cxx_qt_build::{CxxQtBuilder, QmlFile, QmlModule};

/// The Qt modules the editor links. This list is the licensing allowlist from AGENTS.md invariant
/// 12: every entry is offered under the LGPLv3. Adding one needs a licensing check in the PR.
const QT_MODULES: &[&str] = &["Network"];

fn main() {
    // The logo has one source of truth: assets/logo.svg. It is copied next to the QML so it can be
    // part of the QML module's resources.
    println!("cargo:rerun-if-changed=../../assets/logo.svg");
    if let Err(e) = std::fs::copy("../../assets/logo.svg", "qml/logo.svg") {
        println!("cargo:warning=could not copy the logo: {e}");
    }
    write_icon_set();
    let module = QmlModule::new("org.opendesigner.app")
        .qml_file("qml/main.qml")
        .qml_file(QmlFile::from("qml/Theme.qml").singleton(true))
        .qml_file(QmlFile::from("qml/Icons.qml").singleton(true))
        .qml_file(QmlFile::from("qml/IconSet.qml").singleton(true))
        .qml_files([
            "qml/Btn.qml",
            "qml/Icon.qml",
            "qml/Field.qml",
            "qml/JsonModel.qml",
            "qml/VideoPanel.qml",
            "qml/VideoTimeline.qml",
            "qml/VariantsPanel.qml",
            "qml/PreviewPanel.qml",
            "qml/FormatPicker.qml",
            "qml/StartPanel.qml",
            "qml/LayersPanel.qml",
            "qml/InspectorPanel.qml",
            "qml/NotesPanel.qml",
            "qml/HistoryPanel.qml",
            "qml/MemoryPanel.qml",
            "qml/ConnectPanel.qml",
            "qml/AssetPacksSection.qml",
            "qml/DirectionPicker.qml",
            "qml/Dock.qml",
            "qml/DockNode.qml",
            "qml/DockSplit.qml",
            "qml/DockGroup.qml",
            "qml/ChatPanel.qml",
            "qml/CanvasView.qml",
            "qml/CanvasToolbar.qml",
            "qml/ArrangeGroup.qml",
            "qml/AppMenus.qml",
            "qml/SelfTest.qml",
        ]);
    let mut builder = CxxQtBuilder::new_qml_module(module);
    for m in QT_MODULES {
        builder = builder.qt_module(m);
    }
    builder
        .qrc_resources(["qml/logo.svg", "qml/icons/LICENSE"])
        .files(["src/editor.rs"])
        .build();
}

/// Writes `qml/IconSet.qml` (generated, not committed): the drawings in `qml/icons/*.svg` as
/// strings, because QML cannot read its own resource files to tint them. The svg files stay the
/// single source; adding an icon needs no edit elsewhere.
fn write_icon_set() {
    println!("cargo:rerun-if-changed=qml/icons");
    let mut names: Vec<String> = std::fs::read_dir("qml/icons")
        .into_iter()
        .flatten()
        .flatten()
        .filter_map(|e| e.file_name().into_string().ok())
        .filter(|n| n.ends_with(".svg"))
        .collect();
    names.sort();
    let mut qml = String::from(
        "pragma Singleton\nimport QtQuick\n\n// Generated by build.rs from qml/icons/*.svg; do not edit.\nQtObject {\n    readonly property var svgs: ({\n",
    );
    for name in &names {
        let svg = std::fs::read_to_string(format!("qml/icons/{name}")).unwrap_or_default();
        let flat: Vec<&str> = svg
            .lines()
            .map(str::trim)
            .filter(|l| !l.is_empty() && !l.starts_with("<!--"))
            .collect();
        let body = flat.join(" ").replace('\\', "\\\\").replace('"', "\\\"");
        qml.push_str(&format!(
            "        \"{}\": \"{body}\",\n",
            name.trim_end_matches(".svg")
        ));
    }
    qml.push_str("    })\n}\n");
    if let Err(e) = std::fs::write("qml/IconSet.qml", qml) {
        println!("cargo:warning=could not write the icon set: {e}");
    }
}
