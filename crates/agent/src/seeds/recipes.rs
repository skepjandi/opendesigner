//! The six seeds as data: the blocks each one adds, in order, where they sit (fractions of the
//! frame), and the beats the scene is planned around. `super::apply` turns a recipe into one turn.

use serde::Deserialize;
use serde_json::{Value, json};

/// The words and colors a caller may swap in; a seed's own defaults fill the rest.
#[derive(Debug, Clone, Default, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Brand {
    #[serde(default)]
    pub name: Option<String>,
    #[serde(default)]
    pub headline: Option<String>,
    #[serde(default)]
    pub tagline: Option<String>,
    #[serde(default)]
    pub cta: Option<String>,
    #[serde(default)]
    pub accent: Option<String>,
    #[serde(default)]
    pub background: Option<String>,
    #[serde(default)]
    pub foreground: Option<String>,
}

fn or<'a>(given: &'a Option<String>, default: &'a str) -> &'a str {
    given
        .as_deref()
        .map(str::trim)
        .filter(|s| !s.is_empty())
        .unwrap_or(default)
}

/// How a step moves, which the SceneSpec's `motion_plan` records.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum Motion {
    Entrance,
    Ambient,
}

pub enum Step {
    /// An `add_block`; `area` is `[x, y, width, height]` as fractions of the frame.
    Block {
        layer: &'static str,
        level: &'static str,
        role: &'static str,
        block: &'static str,
        at: u64,
        area: Option<[f64; 4]>,
        params: Value,
        depth: Option<f64>,
        motion: Motion,
    },
    /// A 3D device node placed by `[x, y, height]` fractions.
    Device {
        layer: &'static str,
        model: &'static str,
        place: [f64; 3],
    },
    /// An `animate_preset` on a layer's node, or on the camera when `layer` is `None`.
    Move {
        layer: Option<&'static str>,
        preset: &'static str,
        at: u64,
        duration: Option<u64>,
        strength: Option<f64>,
        motion: Motion,
    },
}

pub struct BeatDef {
    pub id: &'static str,
    pub at: u64,
    pub takeaway: &'static str,
    pub focal: &'static str,
    pub transformation: &'static str,
    pub copy: Option<String>,
    pub audio: Option<&'static str>,
    pub exit: Option<u64>,
}

pub struct Recipe {
    pub kind: &'static str,
    pub steps: Vec<Step>,
    pub beats: Vec<BeatDef>,
}

pub struct Seed {
    pub id: &'static str,
    pub name: &'static str,
    pub about: &'static str,
    pub duration_ms: u64,
    pub layouts: &'static str,
    pub recipe: fn(&Brand) -> Recipe,
}

